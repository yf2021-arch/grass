export function stage(p={}){return (p.streak||0)>=4?"習得済み":(p.streak||0)>=1?"定着中":p.attempts?"学習中":"未学習";}

export function flow(p={},mode="auto"){if(mode!=="auto")return mode;return stage(p)==="定着中"&&!p.assistedSinceRecall?"explain":"drill";}

export function grade(p={}, {correct,assisted=false,now=Date.now()}={}){const q={...p,attempts:(p.attempts||0)+1,lastAttempt:now};if(assisted){q.assistedSinceRecall=true;if(!correct){q.streak=0;q.due=now+86400000;}else if(!q.due||q.due<=now)q.due=now+86400000;return q;}q.assistedSinceRecall=false;q.verified=(p.verified||0)+1;if(!correct){q.streak=0;q.due=now+86400000;return q;}q.correct=(p.correct||0)+1;if(!p.due||p.due<=now){q.streak=Math.min(4,(p.streak||0)+1);q.due=now+[1,3,7,14,30][(p.streak||0)>=4?4:q.streak-1]*86400000;}return q;}

export function queue(items,progress,{category="all",size=10,now=Date.now(),newLimit=5}={}){const list=items.filter(x=>category==="all"||x.category===category);const due=list.filter(x=>progress[x.id]?.attempts&&(progress[x.id].due||0)<=now).sort((a,b)=>(progress[a.id].due||0)-(progress[b.id].due||0));const fresh=list.filter(x=>!progress[x.id]?.attempts);return [...due,...fresh.slice(0,newLimit)].slice(0,size);}

export function norm(s){return String(s||"").normalize("NFKC").replace(/[\s、。・「」]/g,"").trim();}

export function question(item,items,p={},format="choice",retry=false,exampleIndex=null){const index=exampleIndex===null?((p.attempts||0)+(retry?1:0))%item.examples.length:exampleIndex%item.examples.length;const example=item.examples[index];const target=example.match(/【([^】]+)】/)[1];const others=items.filter(x=>x.category===item.category&&x.id!==item.id&&x.meaning!==item.meaning);const distract=others.map(x=>x.meaning);for(let i=distract.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[distract[i],distract[j]]=[distract[j],distract[i]];}const options=[item.meaning,...[...new Set(distract)].slice(0,3)];for(let i=options.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[options[i],options[j]]=[options[j],options[i]];}return {example,index,target,options,answer:format==="typing"?target:item.meaning,format};}

